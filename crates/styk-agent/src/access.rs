//! IP access rules in their own nft table (`inet styk_access`), next to Docker's and
//! Cloudflare's tables and never touching them:
//!
//! - an SSH allowlist: when enabled, only listed sources may open port 22;
//! - a blocklist dropped in prerouting, so it also covers Docker's published ports.
//!
//! The config lives in /etc/styk-access.json; /etc/styk-access.nft is generated from it
//! and loaded at boot by styk-access-firewall.service. Comments stay in the JSON and are
//! never written into the nft file.
//!
//! GitHub Actions ranges (sets gh4/gh6) live in /etc/styk-access-github.nft, written daily
//! by styk-access-github-refresh: the agent has no network access to fetch them itself.

use std::net::IpAddr;
use std::path::Path;

use anyhow::{bail, Context, Result};
use styk_proto::{AccessConfig, AccessEntry, AccessState};

use crate::util::{run, try_run};

const CONFIG: &str = "/etc/styk-access.json";
const RULES: &str = "/etc/styk-access.nft";
const GITHUB: &str = "/etc/styk-access-github.nft";
const TABLE: &str = "styk_access";
const MAX_ENTRIES: usize = 2000;

#[derive(Debug, Clone, Copy, PartialEq)]
struct Net {
    v6: bool,
    addr: u128,
    prefix: u8,
}

impl Net {
    fn parse(s: &str) -> Result<Net> {
        let s = s.trim();
        let (ip, prefix) = match s.split_once('/') {
            Some((ip, p)) => (ip, Some(p.parse::<u8>().context("bad prefix")?)),
            None => (s, None),
        };
        let ip: IpAddr = ip
            .parse()
            .with_context(|| format!("not an IP address: {s}"))?;
        let (v6, addr, max) = match ip {
            IpAddr::V4(a) => (false, u32::from(a) as u128, 32),
            IpAddr::V6(a) => (true, u128::from(a), 128),
        };
        let prefix = prefix.unwrap_or(max);
        if prefix > max {
            bail!("prefix too long: {s}");
        }
        let net = Net { v6, addr, prefix };
        Ok(Net {
            addr: net.first(),
            ..net
        })
    }

    fn bits(&self) -> u32 {
        if self.v6 {
            128
        } else {
            32
        }
    }

    fn mask(&self) -> u128 {
        let host = self.bits() - self.prefix as u32;
        let all = if self.v6 { u128::MAX } else { u32::MAX as u128 };
        if host >= 128 {
            0
        } else {
            all & !((1u128 << host) - 1)
        }
    }

    fn first(&self) -> u128 {
        self.addr & self.mask()
    }

    fn overlaps(&self, o: &Net) -> bool {
        if self.v6 != o.v6 {
            return false;
        }
        let p = self.prefix.min(o.prefix);
        let n = Net { prefix: p, ..*self };
        let m = Net { prefix: p, ..*o };
        n.first() == m.first()
    }

    fn render(&self) -> String {
        let ip = if self.v6 {
            IpAddr::from(self.addr.to_be_bytes())
        } else {
            IpAddr::from((self.addr as u32).to_be_bytes())
        };
        if self.prefix as u32 == self.bits() {
            ip.to_string()
        } else {
            format!("{ip}/{}", self.prefix)
        }
    }
}

fn normalize(list: &mut [AccessEntry]) -> Result<Vec<Net>> {
    list.iter_mut()
        .map(|e| {
            let n = Net::parse(&e.cidr)?;
            e.cidr = n.render();
            e.comment = e
                .comment
                .chars()
                .filter(|c| !c.is_control())
                .take(200)
                .collect();
            Ok(n)
        })
        .collect()
}

fn set_body(nets: &[Net], v6: bool) -> String {
    let items: Vec<String> = nets
        .iter()
        .filter(|n| n.v6 == v6)
        .map(Net::render)
        .collect();
    let ty = if v6 { "ipv6_addr" } else { "ipv4_addr" };
    if items.is_empty() {
        format!("type {ty}; flags interval;")
    } else {
        // auto-merge folds overlapping entries instead of failing the load.
        format!(
            "type {ty}; flags interval; auto-merge; elements = {{ {} }}",
            items.join(", ")
        )
    }
}

fn render(cfg_ssh: &[Net], ssh_enabled: bool, github: bool, block: &[Net]) -> String {
    let mut s = format!(
        "# Generated by styk-agent from {CONFIG}; edit in the panel (Security → Access).\n\
         table inet {TABLE}\ndelete table inet {TABLE}\ntable inet {TABLE} {{\n\
         \tset ssh4 {{ {} }}\n\tset ssh6 {{ {} }}\n\tset block4 {{ {} }}\n\tset block6 {{ {} }}\n\
         \tset gh4 {{ type ipv4_addr; flags interval; auto-merge; }}\n\
         \tset gh6 {{ type ipv6_addr; flags interval; auto-merge; }}\n\n\
         \tchain pre {{\n\t\ttype filter hook prerouting priority raw; policy accept;\n\
         \t\tip saddr @block4 counter drop\n\t\tip6 saddr @block6 counter drop\n\t}}\n\n\
         \tchain input {{\n\t\ttype filter hook input priority -10; policy accept;\n\t\tiifname \"lo\" accept\n",
        set_body(cfg_ssh, false),
        set_body(cfg_ssh, true),
        set_body(block, false),
        set_body(block, true),
    );
    if ssh_enabled {
        s.push_str(
            "\t\ttcp dport 22 ct state established,related accept\n\
             \t\ttcp dport 22 ip saddr @ssh4 accept\n\
             \t\ttcp dport 22 ip6 saddr @ssh6 accept\n",
        );
        if github {
            s.push_str(
                "\t\ttcp dport 22 ip saddr @gh4 accept\n\t\ttcp dport 22 ip6 saddr @gh6 accept\n",
            );
        }
        s.push_str("\t\ttcp dport 22 counter drop\n");
    }
    s.push_str("\t}\n}\n");
    s
}

/// CIDRs from Cloudflare's origin table, if present: blocking them would take every site down.
fn cloudflare() -> Vec<Net> {
    let Some(out) = try_run("nft", &["list", "table", "inet", "cf_origin"]) else {
        return Vec::new();
    };
    out.lines()
        .filter_map(|l| l.split_once("elements = {"))
        .flat_map(|(_, rest)| {
            rest.trim_end_matches(['}', ' '])
                .split(',')
                .map(str::trim)
                .map(String::from)
                .collect::<Vec<_>>()
        })
        .filter_map(|c| Net::parse(&c).ok())
        .collect()
}

fn ssh_sessions() -> Vec<String> {
    let out =
        try_run("ss", &["-tnH", "state", "established", "( sport = :22 )"]).unwrap_or_default();
    let mut peers: Vec<String> = out
        .lines()
        .filter_map(|l| l.split_whitespace().nth(3))
        .filter_map(|p| {
            p.rsplit_once(':').map(|(ip, _)| {
                ip.trim_matches(['[', ']'])
                    .trim_start_matches("::ffff:")
                    .to_string()
            })
        })
        .collect();
    peers.sort();
    peers.dedup();
    peers
}

fn counter(table: &str, needle: &str) -> u64 {
    table
        .lines()
        .filter(|l| l.contains(needle) && l.contains("counter packets"))
        .filter_map(|l| {
            l.split("counter packets ")
                .nth(1)?
                .split_whitespace()
                .next()?
                .parse::<u64>()
                .ok()
        })
        .sum()
}

fn load_config() -> Result<AccessConfig> {
    match std::fs::read(CONFIG) {
        Ok(b) => Ok(serde_json::from_slice(&b).context("parse /etc/styk-access.json")?),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(AccessConfig::default()),
        Err(e) => Err(e.into()),
    }
}

/// Number of ranges in the GitHub file and its mtime.
fn github_info() -> (usize, Option<i64>) {
    let Ok(text) = std::fs::read_to_string(GITHUB) else {
        return (0, None);
    };
    let count = text
        .lines()
        .filter(|l| l.starts_with("add element"))
        .map(|l| l.matches(',').count() + 1)
        .sum();
    let mtime = std::fs::metadata(GITHUB)
        .and_then(|m| m.modified())
        .ok()
        .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
        .map(|d| d.as_secs() as i64);
    (count, mtime)
}

pub fn get() -> Result<AccessState> {
    let table = try_run("nft", &["list", "table", "inet", TABLE]).unwrap_or_default();
    let (github_ranges, github_updated) = github_info();
    Ok(AccessState {
        github_ranges,
        github_updated,
        config: load_config()?,
        ssh_dropped: counter(&table, "dport 22 counter"),
        block_dropped: counter(&table, "@block"),
        ssh_sessions: ssh_sessions(),
    })
}

/// Validates, writes and loads the rules. The table is replaced atomically by `nft -f`.
pub fn set(mut cfg: AccessConfig, force: bool) -> Result<AccessState> {
    if cfg.ssh_allow.len() + cfg.block.len() > MAX_ENTRIES {
        bail!("too many entries (max {MAX_ENTRIES})");
    }
    let allow = normalize(&mut cfg.ssh_allow)?;
    let block = normalize(&mut cfg.block)?;
    if cfg.ssh_allow_enabled && allow.is_empty() {
        bail!("SSH allowlist is empty: nobody could connect");
    }
    let cf = cloudflare();
    for b in &block {
        if (!b.v6 && b.prefix < 8) || (b.v6 && b.prefix < 16) {
            bail!("refusing to block such a large network: {}", b.render());
        }
        if let Some(a) = allow.iter().find(|a| a.overlaps(b)) {
            bail!(
                "{} is blocked but also allowed for SSH ({})",
                b.render(),
                a.render()
            );
        }
        if let Some(c) = cf.iter().find(|c| c.overlaps(b)) {
            bail!(
                "{} overlaps Cloudflare {}: every site would go down",
                b.render(),
                c.render()
            );
        }
    }
    if cfg.ssh_allow_enabled && !force {
        let sessions = ssh_sessions();
        let kept = sessions
            .iter()
            .filter_map(|s| Net::parse(s).ok())
            .any(|s| allow.iter().any(|a| a.overlaps(&s)));
        if !sessions.is_empty() && !kept {
            bail!(
                "none of the current SSH sessions ({}) would be allowed",
                sessions.join(", ")
            );
        }
    }

    let rules = render(&allow, cfg.ssh_allow_enabled, cfg.ssh_allow_github, &block);
    // The table is recreated, so the GitHub sets are refilled in the same transaction.
    let github = std::fs::read_to_string(GITHUB).unwrap_or_default();
    let tmp = format!("{RULES}.tmp");
    let apply = format!("{RULES}.apply");
    std::fs::write(&tmp, &rules)?;
    std::fs::write(&apply, format!("{rules}{github}"))?;
    if let Err(e) = run("nft", &["-c", "-f", &apply]) {
        let _ = std::fs::remove_file(&tmp);
        let _ = std::fs::remove_file(&apply);
        return Err(e.context("nft rejected the generated rules"));
    }
    std::fs::rename(&tmp, RULES)?;
    let res = run("nft", &["-f", &apply]);
    let _ = std::fs::remove_file(&apply);
    res?;
    let json = serde_json::to_vec_pretty(&cfg)?;
    std::fs::write(format!("{CONFIG}.tmp"), json)?;
    std::fs::rename(format!("{CONFIG}.tmp"), CONFIG)?;
    if Path::new("/etc/systemd/system/styk-access-firewall.service").exists() {
        let _ = try_run(
            "systemctl",
            &["enable", "--quiet", "styk-access-firewall.service"],
        );
    }
    get()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_and_overlaps() {
        let a = Net::parse("10.1.2.3/16").unwrap();
        assert_eq!(a.render(), "10.1.0.0/16");
        assert!(a.overlaps(&Net::parse("10.1.200.1").unwrap()));
        assert!(!a.overlaps(&Net::parse("10.2.0.1").unwrap()));
        let v6 = Net::parse("2606:4700::/32").unwrap();
        assert!(v6.overlaps(&Net::parse("2606:4700:10::1").unwrap()));
        assert!(!v6.overlaps(&a));
        assert!(Net::parse("::ffff:1.2.3.4").unwrap().v6);
        assert!(Net::parse("1.2.3.4/33").is_err());
        assert!(Net::parse("1.2.3.4; drop").is_err());
        assert_eq!(Net::parse("0.0.0.0/0").unwrap().render(), "0.0.0.0/0");
    }

    #[test]
    fn renders_rules() {
        let allow = vec![Net::parse("203.0.113.7").unwrap()];
        let block = vec![
            Net::parse("45.1.2.0/24").unwrap(),
            Net::parse("2001:db8::/32").unwrap(),
        ];
        let r = render(&allow, true, false, &block);
        assert!(r.contains(
            "set ssh4 { type ipv4_addr; flags interval; auto-merge; elements = { 203.0.113.7 } }"
        ));
        assert!(r.contains("set ssh6 { type ipv6_addr; flags interval; }"));
        assert!(r.contains("elements = { 2001:db8::/32 }"));
        assert!(r.contains("tcp dport 22 counter drop"));
        assert!(!r.contains("saddr @gh4"));
        assert!(render(&allow, true, true, &block).contains("tcp dport 22 ip saddr @gh4 accept"));
        assert!(!render(&allow, false, true, &block).contains("dport 22"));
        let t = "\t\tip saddr @block4 counter packets 12 bytes 1 drop\n\t\ttcp dport 22 counter packets 5 bytes 3 drop";
        assert_eq!(counter(t, "@block"), 12);
        assert_eq!(counter(t, "dport 22 counter"), 5);
    }
}
